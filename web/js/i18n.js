function initialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && DICTS[saved]) return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('bg') ? 'bg' : 'en';
}

let lang = initialLang();
document.documentElement.lang = lang;

export const getLang = () => lang;
export const names = () => NAMES[lang];

export function setLang(next) {
  if (!DICTS[next] || next === lang) return false;
  lang = next;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
  return true;
}

const fill = (text, params) => text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));

// t('lesson.toastMoved', { when: 'tomorrow 15:00' })
export function t(key, params = {}) {
  return fill(DICTS[lang][key] ?? en[key] ?? key, params);
}

// Counted nouns: tn('n.lessons', 3) -> "3 lessons" / "3 урока"
export function tn(key, n, params = {}) {
  return t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...params });
}

// Like t(), but returns HTML and lets params be html`` fragments (e.g. bold words, icons).
export function th(key, params = {}) {
  const parts = (DICTS[lang][key] ?? en[key] ?? key).split(/(\{\w+\})/);
  return html`${parts.map((part) => {
    const m = part.match(/^\{(\w+)\}$/);
    return m ? params[m[1]] ?? '' : part;
  })}`;
}

export const cap = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);

// The API sends error codes; show them in the current language when we can.
export function errorText(code, fallback) {
  const key = `error.${code}`;
  return code && (DICTS[lang][key] || en[key]) ? t(key) : fallback;
}
